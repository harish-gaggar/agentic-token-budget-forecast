# ---- corpus generation ------------------------------------------------------

def _drift(rng: random.Random, kt: str, cx: str,
           p_cx_drift: float = 0.15, p_type_drift: float = 0.07):
    """Apply realistic label drift: the latent type/complexity that drove
    actual token consumption is rarely exactly what a fixed rule predicts."""
    if rng.random() < p_cx_drift:
        i = COMPLEXITY_LEVELS.index(cx)
        delta = rng.choice([-1, 1])
        cx = COMPLEXITY_LEVELS[max(0, min(len(COMPLEXITY_LEVELS) - 1, i + delta))]
    if rng.random() < p_type_drift:
        alts = [t for t in TASK_TYPES if t != kt]
        kt = rng.choice(alts)
    return kt, cx


def build_corpus(n: int = 600, seed: int = 1729) -> List[Dict[str, Any]]:
    """Build a corpus of agentic task descriptions.

    Latent type and complexity are derived by running the same signal-based
    classifier TABF uses, then applying a small amount of label drift to
    simulate real-world disagreement between rule-based predictions and the
    actual token consumption an agent ends up with.
    """
    rng = random.Random(seed)
    out: List[Dict[str, Any]] = []
    for i in range(n):
        _, _, fn = rng.choice(TEMPLATES)
        text = fn(rng)
        sig = extract_signals(text)
        kt, cx = classify(text, sig)
        kt, cx = _drift(rng, kt, cx)
        out.append({
            "id": f"t{i:04d}",
            "text": text,
            "latent_type": kt,
            "latent_complexity_hint": cx,
        })
    return out


def load_corpus(path: str | Path) -> List[Dict[str, Any]]:
    return json.loads(Path(path).read_text())


def save_corpus(corpus: List[Dict[str, Any]], path: str | Path) -> None:
    Path(path).write_text(json.dumps(corpus, indent=2))
